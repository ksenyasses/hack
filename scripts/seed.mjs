// но с чистой кухней и архивом.
const WITH_ORDERS = process.argv.includes("--orders");

const tokens = {};

async function call(token, method, path, body) {
  const res = await fetch(API + path, {
    method,
    headers: {
      "Content-Type": "application/json",
      ...(token ? { Authorization: "Bearer " + token } : {}),
    },
    body: body ? JSON.stringify(body) : undefined,
  });
  const text = await res.text();
  const data = text ? JSON.parse(text) : null;
  if (!res.ok) throw new Error(`${method} ${path} → ${res.status}: ${data?.error ?? text}`);
  return data;
}

// Дата через n дней, в формате YYYY-MM-DD, по местному времени.
function inDays(n) {
  const d = new Date();
  d.setDate(d.getDate() + n);
  return d.getFullYear() + "-" + String(d.getMonth() + 1).padStart(2, "0") + "-" + String(d.getDate()).padStart(2, "0");
}

async function main() {
  console.log(`подключаемся к ${API}\n`);

  for (const login of ["manager", "cook", "waiter"]) {
    const r = await call(null, "POST", "/auth/login", { login, password: "123" });
    tokens[login] = r.token;
  }
  console.log("вошли: manager, cook, waiter\n");

  // 1. Продукты
  const idByName = {};
  const shelfLife = {};
  for (const [name, unit, minStock, shelfLifeDays, qty] of PRODUCTS) {
    const p = await call(tokens.manager, "POST", "/products", { name, unit, minStock, shelfLifeDays });
    idByName[name] = p.id;
    shelfLife[name] = { shelfLifeDays, qty };
  }
  console.log(`1. продуктов: ${PRODUCTS.length}`);

  // 2. Поставки. Срок ставим осмысленный: скоропортящееся едет с коротким.
  let shortIndex = 0;
  const items = PRODUCTS
    .filter(([name]) => !NE_VEZEM.includes(name))
    .map(([name]) => {
      const { shelfLifeDays, qty } = shelfLife[name];
      let days;
      if (SCOROPORTYASCHIE.includes(name)) {
        days = 1 + (shortIndex++ % 3);
      } else {
        days = Math.min(shelfLifeDays, 14);
      }
      return { productId: idByName[name], quantity: qty, expiryDate: inDays(days) };
    });

  const fresh = items.slice(0, Math.floor(items.length / 2));
  const rest = items.slice(Math.floor(items.length / 2));

  await call(tokens.manager, "POST", "/deliveries", {
    number: "П-2001",
    comment: "Скоропортящееся: рыба, зелень, грибы — срок 1–3 дня",
    items: fresh,
  });
  await call(tokens.manager, "POST", "/deliveries", {
    number: "П-2002",
    comment: "Основная поставка: овощи, бакалея, мясо",
    items: rest,
  });
  console.log(`2. поставок: 2 (позиций: ${fresh.length} и ${rest.length})`);
  console.log(`   не привезли: ${NE_VEZEM.join(", ")} — чтобы стоп-лист был не пустым`);

  // 3. Блюда с составом
  const dishIdByName = {};
  for (const [name, recipe] of DISHES) {
    const created = await call(tokens.manager, "POST", "/dishes", {
      name,
      price: 0,
      recipe: recipe.map(([p, per]) => ({ productId: idByName[p], quantityPerPortion: per })),
    });
    dishIdByName[name] = created.id ?? created.dishId ?? created;
  }
  console.log(`3. блюд: ${DISHES.length}`);

  // 4. Заказы — только по запросу. По умолчанию кухня и архив пустые.
  if (!WITH_ORDERS) {
    console.log("4. заказы пропущены (кухня и архив пустые)");
    console.log("   чтобы получить наполненную демонстрацию: node scripts/seed.mjs --orders");
  } else {
    let served = 0, onKitchen = 0, skipped = 0;
    for (const [table, lines, serve] of ORDERS) {
      try {
        const order = await call(tokens.waiter, "POST", "/orders", {
          tableNumber: table,
          serveMode: "AllAtOnce",
          items: lines.map(([dishName, qty]) => ({ dishId: dishIdByName[dishName], quantity: qty })),
        });
        for (const [dishName] of lines) {
          await call(tokens.cook, "PUT", `/orders/${order.id}/items/${dishIdByName[dishName]}/ready`);
        }
        if (serve) {
          await call(tokens.waiter, "POST", `/orders/${order.id}/served`);
          served++;
        } else {
          onKitchen++;
        }
      } catch (e) {
        skipped++;
        console.log(`   заказ пропущен: ${e.message.split("\n")[0]}`);
      }
    }
    console.log(`4. заказов: выдано ${served}, ждут на кухне ${onKitchen}` + (skipped ? `, пропущено ${skipped}` : ""));
  }

  // 5. Итог
  const dishes = await call(tokens.manager, "GET", "/dishes");
  console.log("\nитог:");
  for (const d of dishes) {
    const mark = d.inStopList ? "СТОП-ЛИСТ" : "в меню";
    console.log(`  ${d.name.padEnd(44)} ${String(d.availablePortions).padStart(4)} порций  ${mark}`);
    if (d.reason) console.log(`      ${d.reason}`);
  }
}

main().catch((e) => {
  console.error("ОШИБКА:", e.message);
  process.exit(1);
});